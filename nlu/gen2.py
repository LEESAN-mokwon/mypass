def one(intent, rnd):
    if intent=='remove':
        mid=rnd.choice(list(MENU)); nm=rnd.choice(MENU[mid]['names'])
        return (rnd.choice(PRE)+nm+' '+rnd.choice(REM)).strip(), 'remove', [{'id':mid,'qty':1,'temp':None}]
    a,b = rnd.choice(C[intent]); t=(rnd.choice(a)+' '+rnd.choice(b)).strip()
    return (rnd.choice(PRE)+t).strip(), intent, []
def make(n, seed, p):
    rnd=random.Random(seed); rows=[]
    W=[('order',0.42),('remove',0.08),('checkout',0.08),('cancel',0.08),('help',0.1),('repeat',0.07),('yes',0.06),('no',0.05),('menu',0.06)]
    for _ in range(n):
        r=rnd.random(); acc=0; intent='order'
        for it,w in W:
            acc+=w
            if r<acc: intent=it; break
        text,intent,items = gen_order(rnd) if intent=='order' else one(intent,rnd)
        if p and rnd.random()<0.5: text=noise(text,rnd,p)
        rows.append({'text':text,'intent':intent,'items':items})
    return rows
